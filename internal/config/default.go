package config

import (
	"fmt"
	"strconv"
	"strings"
)

// DefaultTOML renders a configuration file with every default spelled out in
// a comment. When youTrackURL is non-empty it is written as an active
// setting; otherwise the key is left commented out.
func DefaultTOML(youTrackURL string) string {
	var b strings.Builder
	b.WriteString("# ticktack configuration. Uncomment a line to change a default.\n")
	b.WriteString("# The YouTrack token is not stored here; it lives in the OS keychain.\n\n")
	b.WriteString("# Base URL of your YouTrack instance. Must use https (http only for localhost).\n")
	if youTrackURL != "" {
		fmt.Fprintf(&b, "youtrack_url = %s\n\n", strconv.Quote(youTrackURL))
	} else {
		b.WriteString("# youtrack_url = \"https://example.youtrack.cloud\"\n\n")
	}
	b.WriteString("# Presence gaps longer than this end a work block.\n")
	fmt.Fprintf(&b, "# gap_threshold = %q\n\n", DefaultGapThreshold.String())
	b.WriteString("# A presence sample with at least this much idle time is ignored; time after the last input is never booked.\n")
	fmt.Fprintf(&b, "# idle_threshold = %q\n\n", DefaultIdleThreshold.String())
	b.WriteString("# Blocks shorter than this join a same-ticket neighbour or become one block that needs a ticket.\n")
	fmt.Fprintf(&b, "# min_block_duration = %q\n\n", DefaultMinBlockDuration.String())
	b.WriteString("# Context (repository, branch) that was not confirmed for this long is only a suggestion to\n")
	b.WriteString("# confirm in review. \"0\" turns this limit off. A manual pin (`ticktack switch`) does not depend on\n")
	b.WriteString("# it: on the day it was set it counts in full, on the following days it is only a suggestion.\n")
	fmt.Fprintf(&b, "# context_max_age = %q\n\n", DefaultContextMaxAge.String())
	b.WriteString("# Booked durations are rounded to a multiple of this. Must be whole minutes; \"1m\" books exact minutes.\n")
	fmt.Fprintf(&b, "# rounding = %q\n\n", DefaultRounding.String())
	b.WriteString("# Maximum time booked per day.\n")
	fmt.Fprintf(&b, "# daily_cap = %q\n\n", DefaultDailyCap.String())
	b.WriteString("# Set to false to turn the daily cap off: no warning, and sync is never blocked by it.\n")
	b.WriteString("# daily_cap_enabled = true\n\n")
	b.WriteString("# Name the commits of the booked time in the work item text: their subjects are read from the\n")
	b.WriteString("# repository when \"ticktack sync\" runs (at most 5, merge and fixup! commits left out). The text is\n")
	b.WriteString("# kept in the local sync history so \"ticktack undo\" can restore it. false keeps the short summary.\n")
	b.WriteString("# description_from_commits = true\n\n")
	b.WriteString("# Regular expression that extracts a ticket id from a branch name.\n")
	fmt.Fprintf(&b, "# ticket_pattern = %s\n\n", strconv.Quote(DefaultTicketPattern))
	b.WriteString("# Repositories scanned for git history by \"ticktack scan\". Each entry is the root of one\n")
	b.WriteString("# repository (absolute path or starting with ~/); there is no recursive search.\n")
	b.WriteString("# repo_paths = [\"~/Projects/my-repo\"]\n\n")
	b.WriteString("# Folders whose direct subfolders are repositories (a subfolder with .git).\n")
	b.WriteString("# Scanned like repo_paths; also used to match a repository folder to the\n")
	b.WriteString("# YouTrack project of the same name.\n")
	b.WriteString("# repo_roots = [\"~/Projects\", \"~/StudioProjects\"]\n\n")
	b.WriteString("# Time zone for day boundaries (default: system zone).\n# time_zone = \"Europe/Zurich\"\n\n")
	b.WriteString("# Delete the raw events of a day this many days after it, once the day is fully booked (every\n")
	b.WriteString("# confirmed item is in the ledger with the same minutes). \"0\" keeps events. A cleaned day can no\n")
	b.WriteString("# longer be re-derived, reviewed or synced; overrides, ledger and sync history stay. Maximum 3650.\n")
	fmt.Fprintf(&b, "# retention_days = %d\n\n", DefaultRetentionDays)
	b.WriteString("# Tables follow. Top-level keys such as the ones above must stay before the first table.\n\n")
	b.WriteString("# Standard task for time without a ticket. Created by \"ticktack sync\" after one confirmation.\n")
	b.WriteString("# [default_issue]\n")
	b.WriteString("# Project of the catch-all issue. With repo_roots set, one more is created per matching project.\n")
	b.WriteString("# project = \"GENERAL\"\n")
	b.WriteString("# Summary of the catch-all issue.\n")
	b.WriteString("# summary = \"Meetings / Admin\"\n\n")
	b.WriteString("# Periodic git scan by the agent.\n")
	b.WriteString("# [scan]\n")
	b.WriteString("# How often the scan runs (default 15m). It runs only when repo_paths or repo_roots is set, once\n")
	b.WriteString("# at start and then at this interval. \"0\" turns it off; otherwise the minimum is 5m.\n")
	b.WriteString("# interval = \"15m\"\n\n")
	b.WriteString("# Optional window-title hints (off by default). Needs the macOS Accessibility permission.\n")
	b.WriteString("# [titlehint]\n")
	b.WriteString("# true turns the hints on. Titles are read in memory and never stored.\n")
	b.WriteString("# enabled = true\n\n")
	b.WriteString("# Maps an IDE project name to the absolute path of its repository.\n")
	b.WriteString("# [titlehint.projects]\n# \"my-ide-project\" = \"/abs/path/to/repo\"\n\n")
	b.WriteString("# Optional classes for the foreground app, by macOS bundle ID (nothing is listed by default).\n")
	b.WriteString("# \"work\" (an unlisted app) keeps the ticket; \"neutral\" keeps it but only as a suggestion;\n")
	b.WriteString("# \"personal\" ends the time, which is not counted. Only the bundle ID is used, never a title.\n")
	b.WriteString("# Bundle IDs are matched exactly and case-sensitively; listing one app twice, also with different case, is an error.\n")
	b.WriteString("# [app_classes]\n# \"com.tinyspeck.slackmacgap\" = \"neutral\"\n# \"us.zoom.xos\" = \"neutral\"\n# \"com.apple.Music\" = \"personal\"\n\n")
	b.WriteString("# Fixed repository to ticket mappings. The repo is an absolute path or starts with ~/;\n")
	b.WriteString("# the ticket must match ticket_pattern.\n# [[rules]]\n# repo = \"/path/to/repo\"\n# ticket = \"ABC-1\"\n\n")
	b.WriteString("# Optional import from a local ActivityWatch server (loopback only, off by default).\n")
	b.WriteString("# [activitywatch]\n")
	b.WriteString("# true turns the import on.\n")
	b.WriteString("# enabled = false\n")
	b.WriteString("# URL of the ActivityWatch server. Only loopback addresses are accepted.\n")
	fmt.Fprintf(&b, "# url = %s\n", strconv.Quote(DefaultActivityWatchURL))
	b.WriteString("# Restrict the import to buckets of this host (default: every host).\n")
	b.WriteString("# hostname = \"my-mac\"\n\n")
	b.WriteString("# Optional auto mode (off by default). It books a day without a review, and only its explicit\n")
	b.WriteString("# and rule blocks; an item with any lower-tier time stays for review.\n")
	b.WriteString("# [auto]\n")
	b.WriteString("# true | false. The master switch: false turns both modes off.\n")
	b.WriteString("# enabled = false\n")
	b.WriteString("# \"gated\" (default): `ticktack auto` books only once the trust gate is met, that is trusted_days\n")
	b.WriteString("# consecutive reviewed days without a correction. Run it by hand or from your own scheduler.\n")
	b.WriteString("# \"autopilot\": an explicit opt-in that replaces the trust gate. The agent books completed days\n")
	b.WriteString("# itself, every 30 minutes. Days you confirmed in `ticktack review` are never touched, and today\n")
	b.WriteString("# is never booked. To switch the autopilot off, set mode back to \"gated\" or enabled to false.\n")
	b.WriteString("# Any other value is a configuration error.\n")
	fmt.Fprintf(&b, "# mode = %s\n", strconv.Quote(AutoModeGated))
	b.WriteString("# Whole number, at least 1 (default 10). Gated mode only.\n")
	fmt.Fprintf(&b, "# trusted_days = %d\n", DefaultAutoTrustedDays)
	b.WriteString("# Whole number from 1 to 31 (default 7). Autopilot only: how many completed days back the agent looks.\n")
	fmt.Fprintf(&b, "# autopilot_lookback_days = %d\n", DefaultAutopilotLookbackDays)
	return b.String()
}
